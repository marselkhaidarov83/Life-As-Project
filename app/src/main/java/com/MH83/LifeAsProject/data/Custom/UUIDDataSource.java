    public static Hashtable<Long, UUID> GetUUIDs()
    {
        Hashtable<Long, UUID> list = new Hashtable<>();
        ArrayList<UUID> listUUID = getUUIDList();

        Calendar calendar = Calendar.getInstance();
        calendar.set(Calendar.HOUR_OF_DAY, 0);
        calendar.set(Calendar.HOUR, 0);
        calendar.set(Calendar.MINUTE, 0);
        calendar.set(Calendar.SECOND, 0);
        calendar.set(Calendar.MILLISECOND, 0);

        calendar.set(2026, 0, 1);
        for (int i = 0; i < 60; i++)
        {
            Calendar calendar1 = Calendar.getInstance();
            calendar1.set(calendar.get(Calendar.YEAR), calendar.get(Calendar.MONTH), calendar.get(Calendar.DATE),
                    calendar.get(Calendar.HOUR_OF_DAY), calendar.get(Calendar.MINUTE), calendar.get(Calendar.SECOND));
            calendar1.set(Calendar.HOUR, 0);
            calendar1.set(Calendar.MILLISECOND, 0);
            list.put(calendar1.getTime().getTime(), listUUID.get(i));
            calendar.add(Calendar.MONTH, 1);
        }

        return list;
    }
